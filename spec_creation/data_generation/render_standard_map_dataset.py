#!/usr/bin/env python3
"""Render every swept trajectory tile from the local standard-map raster cache.

This script reads ``datasets/trajectories/trajectory_samples.jsonl`` and writes
one 128x128 standard-map render per trajectory tile. It always constructs
``StandardMapTileSource`` with ``offline=True``; missing raster cache entries
are reported and never fetched from the network.

Run from ``mobilitynet-analysis-scripts``::

    python spec_creation/data_generation/render_standard_map_dataset.py
"""

import argparse
import json
import sys
from pathlib import Path

from pyproj import CRS, Transformer


REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from spec_creation.data_generation.raster_tile_viewer import (
    DEFAULT_CACHE_DIR,
    DEFAULT_TRAJECTORY_DIR,
    VIEWER_ZOOM,
)
from spec_creation.data_generation.standard_map_tile_source import (
    DEFAULT_STANDARD_TILE_URL,
    StandardMapTileSource,
    atomic_image,
    standard_map_render,
)


DEFAULT_OUTPUT_DIR = REPOSITORY_ROOT / "datasets" / "standard_map_renders"
DEFAULT_RESOLUTION = 128


def load_records(trajectory_dir):
    """Read timestamped trajectory tiles generated by the sweep script."""
    records_path = Path(trajectory_dir) / "trajectory_samples.jsonl"
    if not records_path.is_file():
        raise ValueError("Trajectory samples were not found: %s" % records_path)
    with records_path.open() as input_file:
        return [json.loads(line) for line in input_file if line.strip()]


def projected_trajectory(record):
    """Project WGS84 trajectory samples into the tile's UTM CRS."""
    transformer = Transformer.from_crs(
        "EPSG:4326", CRS.from_epsg(record["epsg"]), always_xy=True)
    return [
        (*transformer.transform(point["longitude"], point["latitude"]), point["ts"])
        for point in record["tile_points"]
    ]


def render_record(record, source, output_dir, resolution, zoom):
    """Render and atomically save one timestamp-colored trajectory tile."""
    image = standard_map_render(
        record, projected_trajectory(record), resolution, source, zoom)
    output_path = Path(output_dir) / (record["tile_id"] + ".png")
    atomic_image(output_path, image)
    return output_path


def parse_arguments():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trajectory-dir", type=Path, default=DEFAULT_TRAJECTORY_DIR,
                        help="Directory containing trajectory_samples.jsonl")
    parser.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE_DIR,
                        help="Offline StandardMapTileSource cache directory")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR,
                        help="Directory for rendered 128x128 PNGs")
    parser.add_argument("--resolution", type=int, default=DEFAULT_RESOLUTION,
                        help="Square render resolution (default: %(default)s)")
    parser.add_argument("--zoom", type=int, default=VIEWER_ZOOM,
                        help="Cached slippy-map zoom level (default: %(default)s)")
    parser.add_argument("--skip-existing", action="store_true",
                        help="Keep existing output PNGs without rerendering them")
    return parser.parse_args()


def main():
    args = parse_arguments()
    if args.resolution <= 0 or args.zoom < 0:
        raise ValueError("--resolution must be positive and --zoom must be non-negative")

    records = load_records(args.trajectory_dir)
    source = StandardMapTileSource(
        args.cache_dir, DEFAULT_STANDARD_TILE_URL, offline=True, retries=0)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    missing = []
    rendered = 0
    skipped = 0

    for index, record in enumerate(records, start=1):
        output_path = output_dir / (record["tile_id"] + ".png")
        if args.skip_existing and output_path.is_file():
            skipped += 1
            continue
        try:
            render_record(record, source, output_dir, args.resolution, args.zoom)
            rendered += 1
        except FileNotFoundError as error:
            missing.append({"tile_id": record["tile_id"], "error": str(error)})
        if index % 100 == 0 or index == len(records):
            print("Processed %d/%d trajectory tiles." % (index, len(records)))

    report = {
        "resolution": args.resolution,
        "zoom": args.zoom,
        "source_offline": True,
        "record_count": len(records),
        "rendered_count": rendered,
        "skipped_existing_count": skipped,
        "missing_cache_count": len(missing),
        "missing_cache_records": missing,
    }
    report_path = output_dir / "render_report.json"
    with report_path.open("w") as output_file:
        json.dump(report, output_file, indent=2, sort_keys=True)
        output_file.write("\n")

    print("Rendered %d trajectory tiles; skipped %d existing renders." % (rendered, skipped))
    if missing:
        print("%d trajectory tiles require uncached standard-map rasters. Report: %s" %
              (len(missing), report_path))
        raise SystemExit(1)
    print("All trajectory tiles rendered from the offline cache: %s" % output_dir)


if __name__ == "__main__":
    main()
